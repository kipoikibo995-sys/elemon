"""Writes each creature's white "flash" frames, and src/anim_data.h for Hỏa Hổ (the viewer program).

Run after slice_frames.py and align_frames.py (or just run scripts/build_assets.py).
Usage: python make_anim_data.py [slug | element | stage ...]
"""
import json, os
import numpy as np
from PIL import Image

import creatures

HEADER = os.path.join(creatures.ROOT, 'src', 'anim_data.h')
HEADER_UNIT = ('hoa-ho', 'adult')
# shown on the viewer screen; the 5x7 font has no Vietnamese marks yet
LABELS = {'idle': 'DUNG THO', 'punch': 'DAM', 'blast': 'CHIEU LUA', 'hit': 'TRUNG DON', 'faint': 'GUC NGA',
          'victory': 'THANG', 'eat': 'AN', 'happy': 'VUI NHAY', 'tired': 'MET', 'sick': 'OM',
          'sleep': 'NGU', 'wake': 'THUC DAY'}


def flash_frames(fr, names):
    """A frame blended 75% towards white, keeping the magenta colour key."""
    os.makedirs(os.path.join(fr, 'bmp-flash'), exist_ok=True)
    for n in names:
        a = np.array(Image.open(os.path.join(fr, 'bmp', n + '.bmp')).convert('RGB')).astype(np.int32)
        key = (a[..., 0] == 255) & (a[..., 1] == 0) & (a[..., 2] == 255)
        w = (a + (255 - a) * 3 // 4).astype(np.uint8)
        w[key] = (255, 0, 255)
        near = ~key & (w[..., 0] == 255) & (w[..., 1] == 0) & (w[..., 2] == 255)
        w[near] = (254, 0, 254)
        Image.fromarray(w, 'RGB').save(os.path.join(fr, 'bmp-flash', n + '.bmp'))


def main(cid, stage):
    fr = creatures.frames_dir(cid, stage)
    if not os.path.exists(os.path.join(creatures.frames_dir(cid, stage), 'frames.json')):
        print(f'{cid}/{stage}: not sliced yet, skipped')
        return
    meta = json.load(open(os.path.join(fr, 'frames.json')))
    names = meta['frames']
    flash_frames(fr, names)
    print(f'{cid}/{stage}: {len(names)} flash frames')
    if (cid, stage) == HEADER_UNIT:
        write_header(meta, creatures.anims_path(cid, stage))


def write_header(meta, anims_file):
    anims = {k: v for k, v in json.load(open(anims_file, encoding='utf-8')).items()
             if not k.startswith('_')}
    names = meta['frames']
    index = {n: i for i, n in enumerate(names)}
    W, H = meta['canvas']
    ax, ay = meta['anchor']
    L = ['#ifndef HOLUA_ANIM_DATA_H', '#define HOLUA_ANIM_DATA_H', '',
         '/* Generated by scripts/make_anim_data.py from assets/creatures/hoa/hoa-ho/adult/ - do not edit. */', '',
         f'#define FRAME_W {W}', f'#define FRAME_H {H}', f'#define FRAME_AX {ax}', f'#define FRAME_AY {ay}',
         f'#define FRAME_COUNT {len(names)}', '']
    L.append('static const char *const k_frame_file[FRAME_COUNT] = {')
    L += [f'    "{n}",' for n in names] + ['};', '']
    L.append('/* sideways shift that keeps the feet in place (scripts/align_frames.py) */')
    L.append('static const signed char k_frame_align[FRAME_COUNT] = {')
    L.append('    ' + ', '.join(str(meta['align'][n][0]) for n in names))
    L += ['};', '']
    L.append('typedef struct { unsigned char frame; unsigned short ms; signed char x, y, br; '
             'unsigned char shake, flash, keep_x, keep_y; } AnimKey;')
    L.append('typedef struct { const char *id; const char *label; unsigned char loop, first, count; } Anim;')
    L.append('')
    keys, table, first = [], [], 0
    for name, a in anims.items():
        for k in a['keys']:
            keys.append('    {%d, %d, %d, %d, %d, %d, %d, %d, %d},  /* %s %s */' % (
                index[k['f']], k['ms'], k.get('x', 0), k.get('y', 0), k.get('br', 0),
                k.get('shake', 0), k.get('flash', 0), 'x' not in k, 'y' not in k, name, k['f']))
        table.append(f'    {{"{name}", "{LABELS.get(name, name.upper())}", {int(a["loop"])}, {first}, {len(a["keys"])}}},')
        first += len(a['keys'])
    L.append(f'#define ANIM_KEY_COUNT {len(keys)}')
    L.append('static const AnimKey k_anim_keys[ANIM_KEY_COUNT] = {')
    L += keys + ['};', '']
    L.append(f'#define ANIM_COUNT {len(table)}')
    L.append('static const Anim k_anims[ANIM_COUNT] = {')
    L += table + ['};', '']
    L += ['#endif', '']
    os.makedirs(os.path.dirname(HEADER), exist_ok=True)
    open(HEADER, 'w', newline='\n').write('\n'.join(L))
    print(f'{HEADER}: {len(names)} frames, {len(table)} animations, {len(keys)} keys')


if __name__ == '__main__':
    for cid, stage in creatures.selected():
        main(cid, stage)
